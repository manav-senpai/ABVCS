"""
Data models and schemas for ABVCS agent payloads and Git operations.
"""

from typing import List, Optional, Literal, Dict, Any, Tuple

try:
    from pydantic import BaseModel, Field
    HAS_PYDANTIC = True
except ImportError:
    HAS_PYDANTIC = False
    class BaseModel:
        def __init__(self, **kwargs):
            for k, v in kwargs.items():
                setattr(self, k, v)
        def dict(self):
            return self.__dict__
    def Field(*args, **kwargs):
        default = kwargs.get("default", None)
        if "default_factory" in kwargs:
            return kwargs["default_factory"]()
        return default


class FileDelta(BaseModel):
    """Represents changes detected in a single repository file."""
    file_path: str
    status: Literal["modified", "added", "deleted", "untracked"]
    lines_added: int = 0
    lines_deleted: int = 0
    patch: Optional[str] = None


class SemanticUnit(BaseModel):
    """Group of related changes representing a coherent logical task."""
    unit_id: str
    category: Literal["feat", "fix", "refactor", "test", "docs", "chore", "perf"]
    files: List[str]
    description: str
    confidence: float = Field(default=0.95)


class CommitProposal(BaseModel):
    """Structured commit proposal generated by CommitPlannerAgent."""
    commit_type: Literal["feat", "fix", "docs", "style", "refactor", "perf", "test", "chore"]
    scope: Optional[str] = None
    subject: str = Field(default="")
    body: List[str] = Field(default_factory=list)
    files_to_stage: List[str] = Field(default_factory=list)
    breaking_change: bool = False
    confidence_score: float = Field(default=0.95)

    @property
    def formatted_message(self) -> str:
        """Formats the commit into a standard Conventional Commit string."""
        prefix = f"{self.commit_type}"
        if self.scope:
            prefix += f"({self.scope})"
        if self.breaking_change:
            prefix += "!"
        header = f"{prefix}: {self.subject}"
        
        if not self.body:
            return header
            
        body_text = "\n".join(f"- {point}" for point in self.body)
        return f"{header}\n\n{body_text}"


class SecurityIssue(BaseModel):
    """Individual security or quality issue identified during review."""
    file_path: str
    line_number: Optional[int] = None
    severity: Literal["INFO", "WARNING", "CRITICAL"] = "INFO"
    rule_id: str = "SEC-001"
    description: str = ""
    suggested_fix: str = ""


class SecurityAuditReport(BaseModel):
    """Aggregate security report from the Review & Security Auditor Agent."""
    status: Literal["PASSED", "WARNINGS", "BLOCKED"] = "PASSED"
    score: int = Field(default=100)
    issues: List[SecurityIssue] = Field(default_factory=list)
    summary: str = ""


class ConflictChunk(BaseModel):
    """Parsed conflict block in a file."""
    file_path: str
    start_line: int
    ours_content: str
    theirs_content: str
    base_content: Optional[str] = None


class ConflictResolutionResult(BaseModel):
    """Suggested merge conflict resolution."""
    file_path: str
    resolved_content: str
    strategy: Literal["ours", "theirs", "synthesized"]
    explanation: str
    confidence: float = Field(default=0.95)
